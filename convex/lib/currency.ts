export function normalizeCurrencyCode(code: string | undefined) {
  const normalized = (code?.trim().toUpperCase() || DEFAULT_CURRENCY);
  if (!/^[A-Z]{3}$/.test(normalized)) {
    throw new Error("Currency must be a 3-letter ISO code (e.g. USD).");
  }
  if (!VALID.has(normalized)) {
    throw new Error(`Unsupported currency code: ${normalized}`);
  }
  return normalized;
}

export function currencyOrDefault(code: string | undefined) {
  if (!code) return DEFAULT_CURRENCY;
  return VALID.has(code.toUpperCase()) ? code.toUpperCase() : DEFAULT_CURRENCY;
}
