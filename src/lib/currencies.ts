export type CurrencyCode = (typeof ALL_CURRENCY_CODES)[number];

const displayNames =
  typeof Intl !== "undefined"
    ? new Intl.DisplayNames(["en"], { type: "currency" })
    : null;

export function getCurrencyLabel(code: string) {
  const upper = code.toUpperCase();
  const named = displayNames?.of(upper);
  return named && named !== upper ? `${upper} — ${named}` : upper;
}

export function formatMoney(amount: number, currency: string = DEFAULT_CURRENCY, locale = "en") {
  const code = currency.toUpperCase() || DEFAULT_CURRENCY;
  try {
    return new Intl.NumberFormat(locale, {
      style: "currency",
      currency: code,
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    }).format(amount);
  } catch {
    return `${code} ${amount.toFixed(2)}`;
  }
}

export function isValidCurrencyCode(code: string) {
  return ALL_CURRENCY_CODES.includes(code.toUpperCase() as CurrencyCode);
}

export const OTHER_CURRENCY_CODES = ALL_CURRENCY_CODES.filter(
  (c) => !(POPULAR_CURRENCIES as readonly string[]).includes(c),
);
